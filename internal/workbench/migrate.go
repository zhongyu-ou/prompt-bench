package workbench

import (
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
)

func migrateEvaluations(tx *sql.Tx) error {
	if _, err := tx.Exec(`CREATE TABLE evaluations (id TEXT PRIMARY KEY, generation_run_id TEXT NOT NULL REFERENCES batches(id), created_at TEXT NOT NULL, summary BYTEA NOT NULL, snapshot BYTEA NOT NULL)`); err != nil {
		return err
	}
	_, err := tx.Exec(`CREATE TABLE evaluation_outcomes (evaluation_id TEXT NOT NULL REFERENCES evaluations(id), seq INTEGER NOT NULL, result_id TEXT NOT NULL REFERENCES results(id), metric_id TEXT NOT NULL, round INTEGER NOT NULL, data BYTEA NOT NULL, PRIMARY KEY(evaluation_id,result_id,metric_id,round), UNIQUE(evaluation_id,seq))`)
	return err
}

const postgresSchemaVersion = 2

func (s *Store) migrate() error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	var exists bool
	if err = tx.QueryRow("SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname=current_schema() AND tablename='schema_version')").Scan(&exists); err != nil {
		return err
	}
	if exists {
		var count, version int
		if err = tx.QueryRow("SELECT count(*), COALESCE(max(version),0) FROM schema_version WHERE id=1").Scan(&count, &version); err != nil {
			return err
		}
		var total int
		if err = tx.QueryRow("SELECT count(*) FROM schema_version").Scan(&total); err != nil {
			return err
		}
		if count != 1 || total != 1 {
			return errors.New("database schema version row is missing or invalid")
		}
		if version > postgresSchemaVersion {
			return errors.New("database schema is newer than this Promptbench binary supports; use a newer binary")
		}
		if version == 1 {
			if err := migrateEvaluations(tx); err != nil {
				return err
			}
			if _, err := tx.Exec("UPDATE schema_version SET version=2 WHERE id=1"); err != nil {
				return err
			}
		} else if version != postgresSchemaVersion {
			return fmt.Errorf("unsupported PostgreSQL schema version %d", version)
		}
		return tx.Commit()
	}
	var tables int
	if err = tx.QueryRow("SELECT count(*) FROM pg_tables WHERE schemaname=current_schema()").Scan(&tables); err != nil {
		return err
	}
	if tables != 0 {
		return errors.New("database schema contains tables but has no schema version; refusing initialization")
	}
	statements := []string{
		`CREATE TABLE schema_version (id SMALLINT PRIMARY KEY CHECK(id=1), version INTEGER NOT NULL)`,
		`CREATE TABLE state (id INTEGER PRIMARY KEY CHECK(id=1), version BIGINT NOT NULL, data BYTEA NOT NULL)`,
		`CREATE TABLE batches (id TEXT PRIMARY KEY, created_at TEXT NOT NULL, summary BYTEA NOT NULL, snapshot BYTEA NOT NULL)`,
		`CREATE TABLE results (id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES batches(id), seq INTEGER NOT NULL, group_id TEXT NOT NULL, case_id TEXT NOT NULL, iteration INTEGER NOT NULL, data BYTEA NOT NULL, UNIQUE(batch_id,group_id,case_id,iteration))`,
		`CREATE TABLE credentials (ref TEXT PRIMARY KEY, ciphertext BYTEA NOT NULL)`,
		`CREATE TABLE migration_archives (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, from_version INTEGER NOT NULL, state_data BYTEA NOT NULL)`,
		`CREATE INDEX results_batch ON results(batch_id,seq)`,
	}
	for _, statement := range statements {
		if _, err = tx.Exec(statement); err != nil {
			return err
		}
	}
	state, err := seedState()
	if err != nil {
		return err
	}
	data, err := json.Marshal(state)
	if err != nil {
		return err
	}
	if _, err = tx.Exec("INSERT INTO state(id,version,data) VALUES(1,$1,$2)", state.Version, data); err != nil {
		return err
	}
	if err := migrateEvaluations(tx); err != nil {
		return err
	}
	if _, err = tx.Exec("INSERT INTO schema_version(id,version) VALUES(1,$1)", postgresSchemaVersion); err != nil {
		return err
	}
	return tx.Commit()
}
